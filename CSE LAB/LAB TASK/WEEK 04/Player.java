public class Player {
    private String name;
    private int age;
    private int match;
    public Player(String n,int a,int m){
        name = n;
        age = a;
        match = m;
    }
    public String getName(){
        return name;
    }
    public int getAge(){
        return age;
    }public int getMatch(){
        return match;
    }
}
